/* FLOW gradient loop — standalone port of the React gradient engine's FLOW renderer.
   Source: "Generated by scripts/build-react-gradient-engine.mjs" (paintRecipe / FLOW branch).
   Pure canvas, no React — for the static portfolio hero (光幕 layer). */
(function () {
  'use strict';

  var SE = 20.75, QC = 3.5, YR = 0.2;

  function Fe(hex) { var t = parseInt(hex.slice(1), 16); return [t >> 16 & 255, t >> 8 & 255, t & 255]; }
  function clamp01(e) { return e < 0 ? 0 : e > 1 ? 1 : e; }
  function de(e) { var t = clamp01(e); return t * t * (3 - 2 * t); }
  function Ze(hex) {
    var c = Fe(hex).map(function (v) { var r = v / 255; return r <= 0.04045 ? r / 12.92 : Math.pow((r + 0.055) / 1.055, 2.4); });
    return Gn(c[0], c[1], c[2], [0, 0, 0]);
  }
  function Gn(e, t, n, a) {
    var o = Math.cbrt(0.4122214708 * e + 0.5363325363 * t + 0.0514459929 * n),
        r = Math.cbrt(0.2119034982 * e + 0.6806995451 * t + 0.1073969566 * n),
        s = Math.cbrt(0.0883024619 * e + 0.2817188376 * t + 0.6299787005 * n);
    a[0] = 0.2104542553 * o + 0.793617785 * r - 0.0040720468 * s;
    a[1] = 1.9779984951 * o - 2.428592205 * r + 0.4505937099 * s;
    a[2] = 0.0259040371 * o + 0.7827717662 * r - 0.808675766 * s;
    return a;
  }
  function Rt(e, t, n) {
    var a = Math.pow(e + 0.3963377774 * t + 0.2158037573 * n, 3),
        o = Math.pow(e - 0.1055613458 * t - 0.0638541728 * n, 3),
        r = Math.pow(e - 0.0894841775 * t - 1.291485548 * n, 3);
    return [4.0767416621 * a - 3.3077115913 * o + 0.2309699292 * r,
            -1.2684380046 * a + 2.6097574011 * o - 0.3413193965 * r,
            -0.0041960863 * a - 0.7034186147 * o + 1.707614701 * r].map(function (i) {
      var l = i <= 0.0031308 ? i * 12.92 : 1.055 * Math.pow(Math.max(0, i), 1 / 2.4) - 0.055;
      return Math.min(255, Math.max(0, Math.round(l * 255)));
    });
  }
  function Dn(e, t) {
    var n = e * 0.37, a = 0.6 + (e / 3 - Math.floor(e / 3)) * 0.9, o = 0.8 + (((e + 1) / 4) - Math.floor((e + 1) / 4));
    return [0.5 + 0.5 * Math.sin(t * a + n), 0.5 + 0.5 * Math.cos(t * o + n * 1.5)];
  }
  function dn(e) { return Array.from({ length: Math.max(0, e - 1) }, function (t, n) { return (n + 1) / e; }); }
  function Wt(e, t) { return [0].concat(t && t.length === e - 1 ? t : dn(e), [1]); }
  function un(e, t, n) { var a = Wt(e, t); return (a[n + 1] - a[n]) * e; }

  var _img = new WeakMap();
  function st(ctx, w, h) {
    var a = _img.get(ctx);
    if (!a || a.width !== w || a.height !== h) { a = ctx.createImageData(w, h); _img.set(ctx, a); }
    return a;
  }

  /* FLOW renderer (faithful port of R2). i=false (true-colour path). */
  function paintFlow(ctx, w, h, stops, divs, params, time) {
    var n = stops.length,
        c = stops.map(Ze),
        u = params.distortion / 100,
        p = params.swirl / 100,
        m = 0.4 + params.scale / 100 * 1.2,
        hpos = stops.map(function (_, L) { return Dn(L, time); }),
        g = stops.map(function (_, L) { return un(n, divs, L); }),
        img = st(ctx, w, h), data = img.data;
    for (var y = 0; y < h; y++) {
      var L = (y + 0.5) / h;
      for (var A = 0; A < w; A++) {
        var R = ((A + 0.5) / w - 0.5) / m + 0.5,
            x = (L - 0.5) / m + 0.5,
            k = de(Math.hypot(R - 0.5, x - 0.5)),
            S = 1 - k;
        for (var O = 1; O <= 2; O++) {
          R += u * S / O * Math.sin(time + O * 0.4 * de(x)) * Math.cos(0.2 * time + O * 2.4 * de(x));
          x += u * S / O * Math.cos(time + O * 2 * de(R));
        }
        var F = 3 * p * k, M = Math.cos(-F), E = Math.sin(-F), v = R - 0.5, wv = x - 0.5;
        R = M * v - E * wv + 0.5; x = E * v + M * wv + 0.5;
        var C = 0, N = 0, I = 0, P = 0;
        for (var q = 0; q < n; q++) {
          var D = R - hpos[q][0], dd = x - hpos[q][1], _ = D * D + dd * dd,
              H = g[q] / (Math.pow(_, QC / 2) + 1e-4);
          C += c[q][0] * H; N += c[q][1] * H; I += c[q][2] * H; P += H;
        }
        var T = 1 / Math.max(1e-4, P), B = Rt(C * T, N * T, I * T), G = (y * w + A) * 4;
        data[G] = B[0]; data[G + 1] = B[1]; data[G + 2] = B[2]; data[G + 3] = 255;
      }
    }
    ctx.putImageData(img, 0, 0);
  }

  var RECIPE = {
    /* default recipe from "Untitled blend.jsx" — type FLOW, name "Untitled blend" */
    stops: ['#EAF4FC', '#7199DB', '#CF8FBE', '#9876DA'],
    divs: [0.25, 0.5, 0.75],
    params: { scale: 50, distortion: 60, swirl: 10 },
    speed: 30,          /* 0..100 */
    startT: 184.03787696010832,
    maxDim: 380         /* render resolution cap (gradient is soft; CSS upscales) */
  };

  function attach(layer, options) {
    if (!layer) return null;
    var opt = Object.assign({}, RECIPE, options || {});
    var hero = document.querySelector('.hero-v2x');
    layer.classList.add('has-canvas');
    var canvas = layer.querySelector('canvas.flow-canvas');
    if (!canvas) {
      canvas = document.createElement('canvas');
      canvas.className = 'flow-canvas aurora-canvas';
      canvas.setAttribute('aria-hidden', 'true');
      canvas.style.cssText = 'position:absolute;inset:0;display:block;width:100%;height:100%';
      layer.appendChild(canvas);
    }
    var ctx = canvas.getContext('2d');
    var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    var visible = true, raf = 0, last = 0;
    var t0 = performance.now();

    function timeNow() {
      var sec = reduce ? 0 : (performance.now() - t0) / 1000;
      return opt.startT + sec * (opt.speed / 100) * 1.2;
    }
    function size() {
      var rect = layer.getBoundingClientRect();
      var W = Math.max(2, rect.width), H = Math.max(2, rect.height);
      var scale = Math.min(1, opt.maxDim / Math.max(W, H));
      canvas.width = Math.round(W * scale);
      canvas.height = Math.round(H * scale);
      return [canvas.width, canvas.height];
    }
    function draw() {
      var s = size();
      paintFlow(ctx, s[0], s[1], opt.stops, opt.divs, opt.params, timeNow());
    }
    function active() { return visible && !document.hidden && (!hero || hero.getAttribute('data-bg') === 'aurora'); }
    function frame(now) {
      raf = 0;
      if (!active()) return;
      raf = requestAnimationFrame(frame);
      if (now - last < 50) return;   /* ~20fps */
      last = now;
      draw();
    }
    function sync() {
      if (!active()) { if (raf) cancelAnimationFrame(raf); raf = 0; }
      else if (!raf) { last = 0; raf = requestAnimationFrame(frame); }
    }
    if ('IntersectionObserver' in window) {
      new IntersectionObserver(function (en) { visible = en[en.length - 1].isIntersecting; sync(); }).observe(layer);
    }
    document.addEventListener('visibilitychange', sync);
    window.addEventListener('resize', function () { draw(); });
    if (hero && 'MutationObserver' in window) {
      new MutationObserver(sync).observe(hero, { attributes: true, attributeFilter: ['data-bg'] });
    }
    var mo = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)');
    mo && mo.addEventListener && mo.addEventListener('change', function (e) { reduce = e.matches; draw(); sync(); });
    draw();
    sync();
    return { canvas: canvas, redraw: draw };
  }

  window.FLOW_GRADIENT = { attach: attach, paintFlow: paintFlow, RECIPE: RECIPE };
})();
